const { chromium } = require('playwright');
const assert = require('assert');
const BASE = (process.env.BASE_URL || 'http://127.0.0.1:8000') + '/index.html';
(async () => {
  const browser = await chromium.launch();
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, locale: 'pt-BR' });
  const page = await context.newPage();
  page.setDefaultTimeout(5000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(BASE, { waitUntil: 'domcontentloaded' });
  await page.locator('button[data-modulo="xpt"]').click();
  await page.locator('#xo-nova').click();
  await page.locator('#xh-ok').click();
  await page.locator('button[data-aba="quantidades"]').click();
  const storageAntes = await page.evaluate(() => localStorage.getItem('melinotepad_xpt_v1'));
  const input = page.locator('#xq-arquivo-input');
  await input.setInputFiles({ name: 'teste.csv', mimeType: 'text/csv', buffer: Buffer.from('coluna\nvalor') });
  assert.match(await page.locator('#xq-arquivo-estado').innerText(), /teste\.csv/);
  assert.match(await page.locator('#xq-arquivo-estado').innerText(), /bytes|KB|MB/);
  assert.match(await page.locator('#xq-arquivo-estado').innerText(), /ainda não foi lido nem importado/);
  await page.locator('#xq-arquivo-outro').click();
  await input.setInputFiles({ name: 'outra.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: Buffer.from('xlsx-placeholder') });
  assert.match(await page.locator('#xq-arquivo-estado').innerText(), /outra\.xlsx/);
  await page.locator('#xq-arquivo-remover').click();
  assert.match(await page.locator('#xq-arquivo-estado').innerText(), /Nenhum arquivo selecionado/);
  await input.setInputFiles({ name: 'nao-suportado.pdf', mimeType: 'application/pdf', buffer: Buffer.from('pdf') });
  assert.match(await page.locator('#xq-arquivo-estado').innerText(), /Formato não suportado/);
  assert.equal(await page.locator('#xq-arquivo-estado .xpt-importacao__arquivo').count(), 0, 'arquivo inválido não fica pronto');
  await input.setInputFiles({ name: 'vazio.csv', mimeType: 'text/csv', buffer: Buffer.alloc(0) });
  assert.match(await page.locator('#xq-arquivo-estado').innerText(), /vazio ou não pôde ser recebido/);
  await page.evaluate(() => {
    const area = document.querySelector('#xq-area-importacao');
    const transfer = new DataTransfer();
    transfer.items.add(new File(['arrastado'], 'arrastado.csv', { type: 'text/csv' }));
    area.dispatchEvent(new DragEvent('dragenter', { bubbles: true, cancelable: true, dataTransfer: transfer }));
    if (!area.classList.contains('is-arrastando')) throw new Error('indicador de arrastar não apareceu');
    area.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: transfer }));
  });
  assert.match(await page.locator('#xq-arquivo-estado').innerText(), /arrastado\.csv/);
  assert.equal(await page.evaluate(() => localStorage.getItem('melinotepad_xpt_v1')), storageAntes, 'selecionar arquivo não altera dados existentes');
  assert.deepEqual(errors, [], 'sem erros JavaScript');
  await browser.close();
  console.log('PASS XPT importação inicial: seleção, substituição, remoção, arrastar/soltar, validação e preservação dos dados.');
})().catch(e => { console.error(e); process.exit(1); });
