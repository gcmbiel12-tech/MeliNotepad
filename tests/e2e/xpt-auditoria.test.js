const { chromium } = require('playwright');
const assert = require('assert');
const BASE = (process.env.BASE_URL || 'http://127.0.0.1:8000') + '/index.html';
(async () => {
  const browser = await chromium.launch();
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, locale: 'pt-BR' });
  const page = await context.newPage();
  await page.addInitScript(() => { window.print = () => {}; });
  page.setDefaultTimeout(5000);
  page.setDefaultNavigationTimeout(10000);
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  console.log('ETAPA 1: abrir aplicação');
  await page.goto(BASE, { waitUntil: 'domcontentloaded' });
  await page.locator('[data-abrir-modulo="xpt"]').click();
  await page.locator('#summary-xpt-operacoes').click();
  await page.locator('#xo-nova').click();
  await page.locator('#xh-ok').click();
  await page.locator('button[data-aba="gaiolas"]').click();
  await page.locator('#xg-adicionar').click();
  await page.locator('#xc-texto').fill('1001,1002');
  await page.locator('#xc-ok').click();
  assert.equal(await page.locator('#xg-corpo tr').count(), 2, 'duas rotas cadastradas');
  await page.locator('#xg-corpo tr').filter({ hasText: '1001' }).locator('button[data-acao="auditar"]').click();
  await page.locator('dialog[open] #xa-auditor').fill('Auditor Teste');
  await page.locator('dialog[open] #xa-q-g').fill('3');
  await page.locator('dialog[open] #xa-q-v').fill('2');
  await page.locator('dialog[open] #xa-q-p').fill('4');
  await page.locator('dialog[open] #xa-ok').click();
  assert.match(await page.locator('#xg-corpo tr').filter({ hasText: '1001' }).innerText(), /Concluído/);
  await page.locator('#xg-corpo tr').filter({ hasText: '1001' }).locator('button[data-acao="auditar"]').click();
  assert.match(await page.locator('dialog[open] h2').innerText(), /Abrir auditoria/);
  await page.locator('dialog[open] button').filter({ hasText: 'Cancelar' }).click();
  const linha = page.locator('#xg-corpo tr').filter({ hasText: '1001' });
  assert.match(await linha.innerText(), /G3 \| V2 \| P4/);
  assert.match(await linha.innerText(), /Concluído/);
  await page.reload();
  if (await page.locator('#tela-app').isVisible()) await page.locator('[data-abrir-modulo="xpt"]').click();
  await page.locator('#summary-xpt-operacoes').click();
  // Reabrir explicitamente a operação persistida após a recarga.
  const abrirOperacao = page.locator('#xo-corpo-ops button[data-acao="abrir"]').first();
  if (await abrirOperacao.count()) await abrirOperacao.click({ force: true });
  else await page.locator('.xpt-lista-mobile button[data-acao="abrir"]').first().click({ force: true });
  // Abrir a aba de gaiolas somente depois de reabrir a operação.
  await page.locator('button[data-aba="gaiolas"]').click();
  await page.locator('#xg-corpo').waitFor({ state: 'visible' });
  assert.match(await page.locator('#xg-corpo tr').filter({ hasText: '1001' }).innerText(), /G3 \| V2 \| P4/);
  // Validar auditoria em lote com G/V/P, persistência e ausência de duplicação.
  await page.locator('#xg-lote').click();
  await page.locator('dialog[open] #xc-texto').fill('1002');
  await page.locator('dialog[open] #xa-lote-g').fill('5');
  await page.locator('dialog[open] #xa-lote-v').fill('1');
  await page.locator('dialog[open] #xa-lote-p').fill('2');
  await page.locator('dialog[open] #xa-auditor').fill('Auditor Lote');
  await page.locator('dialog[open] #xc-ok').click();
  const linhaLote = page.locator('#xg-corpo tr').filter({ hasText: '1002' });
  assert.match(await linhaLote.innerText(), /G5 \| V1 \| P2/);
  assert.match(await linhaLote.innerText(), /Concluído/);
  await page.reload();
  if (await page.locator('#tela-app').isVisible()) await page.locator('[data-abrir-modulo="xpt"]').click();
  await page.locator('#summary-xpt-operacoes').click();
  const abrirDepoisLote = page.locator('#xo-corpo-ops button[data-acao="abrir"]').first();
  if (await abrirDepoisLote.count()) await abrirDepoisLote.click({ force: true });
  else await page.locator('.xpt-lista-mobile button[data-acao="abrir"]').first().click({ force: true });
  await page.locator('button[data-aba="gaiolas"]').click();
  assert.equal(await page.locator('#xg-corpo tr').filter({ hasText: '1002' }).count(), 1, 'lote não duplica rota');
  assert.match(await page.locator('#xg-corpo tr').filter({ hasText: '1002' }).innerText(), /G5 \| V1 \| P2/, 'G/V/P do lote persistem após recarga');
  await page.locator('#xg-filtro').selectOption('concluida_sem_divergencia');
  assert.equal(await page.locator('#xg-corpo tr').count(), 2, 'filtro status concluído sem divergência inclui auditoria individual e em lote');
  await page.locator('#xg-filtro').selectOption('*');
  await page.locator('#xg-busca').fill('Auditor Teste');
  assert.equal(await page.locator('#xg-corpo tr').count(), 1, 'busca por auditor');

  // Validar resumo por veículo e finalização independente com horário editável.
  await page.locator('button[data-aba="veiculos"]').click();
  await page.locator('#xv-placa').fill('ABC1234');
  await page.locator('#xv-form button[type="submit"]').click();
  await page.locator('#xv-placa').fill('DEF5678');
  await page.locator('#xv-form button[type="submit"]').click();
  await page.locator('button[data-aba="gaiolas"]').click();
  await page.locator('#xg-busca').fill('');
  await page.locator('select[aria-label="Veículo da gaiola 1001"]').first().selectOption({ label: 'ABC1234' });
  await page.locator('select[aria-label="Veículo da gaiola 1002"]').first().selectOption({ label: 'ABC1234' });
  await page.locator('button[data-aba="veiculos"]').click();
  const veiculos = page.locator('.xpt-veiculo');
  assert.equal(await veiculos.count(), 2, 'dois veículos cadastrados');
  assert.match(await veiculos.nth(0).innerText(), /Carregamento pendente/);
  assert.equal(await veiculos.nth(0).locator('input[data-acao="foto-veiculo"][data-tipo="hand"]').count(), 1, 'foto HAND opcional disponível por veículo');
  assert.equal(await veiculos.nth(0).locator('input[data-acao="foto-veiculo"][data-tipo="carreta"]').count(), 1, 'foto carreta opcional disponível por veículo');
  assert.match(await veiculos.nth(0).innerText(), /Rotas carregadas: 2 · Gaiolas informadas: 11 · Paletes informados: 6/);
  await veiculos.nth(0).locator('button[data-acao="fim-veiculo"]').click();
  await page.locator('dialog[open] #xh-ok').click();
  assert.match(await veiculos.nth(0).innerText(), /Carregamento finalizado:/);
  assert.match(await veiculos.nth(0).innerText(), /Carregamento concluído/);
  assert.equal(await veiculos.nth(0).locator('.xpt-carregamento-status--concluido').count(), 1, 'status concluído usa a classe visual verde');
  assert.match(await veiculos.nth(0).innerText(), /Editar horário de finalização/);
  assert.match(await veiculos.nth(1).innerText(), /Carregamento ainda não finalizado/);
  await veiculos.nth(0).locator('button[data-acao="fim-veiculo"]').click();
  assert.match(await page.locator('dialog[open] h2').innerText(), /Editar finalização/);
  await page.locator('dialog[open] button').filter({ hasText: 'Cancelar' }).click();
  const pngTeste = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jY9sAAAAASUVORK5CYII=', 'base64');
  await veiculos.nth(0).locator('input[data-acao="foto-veiculo"][data-tipo="hand"]').setInputFiles({ name: 'hand.png', mimeType: 'image/png', buffer: pngTeste });
  await page.getByText('Foto registrada').first().waitFor({ state: 'visible' });
  await veiculos.nth(0).locator('input[data-acao="foto-veiculo"][data-tipo="carreta"]').setInputFiles({ name: 'carreta.png', mimeType: 'image/png', buffer: pngTeste });
  await page.getByText('Foto registrada').nth(1).waitFor({ state: 'visible' });
  await page.locator('button[data-aba="relatorios"]').click();
  const textoRelatorio = await page.locator('#xo-relatorios pre.texto-relatorio').innerText();
  assert.ok(!textoRelatorio.includes('Início:'), 'relatório não exibe horário de início');
  assert.ok(textoRelatorio.includes('Rotas carregadas: 2') && textoRelatorio.includes('Gaiolas informadas: 11') && textoRelatorio.includes('Paletes informados: 6'), 'relatório separa rotas, gaiolas e paletes');
  await page.locator('button').filter({ hasText: 'Gerar PDF do relatório básico (com fotos)' }).click();
  await page.locator('#print-area img').nth(1).waitFor({ state: 'attached' });
  assert.equal(await page.locator('#print-area img').count(), 2, 'relatório básico inclui fotos HAND e carreta');
  assert.match(await page.locator('#print-area img').nth(0).getAttribute('alt'), /HAND/);
  assert.match(await page.locator('#print-area img').nth(1).getAttribute('alt'), /carreta/);
  await page.locator('#xo-relatorios button').filter({ hasText: 'Gerar PDF / imprimir relatório detalhado' }).click();
  await page.locator('#print-area img').nth(1).waitFor({ state: 'attached' });
  assert.equal(await page.locator('#print-area img').count(), 2, 'relatório completo inclui fotos HAND e carreta');
  await page.locator('button[data-aba="veiculos"]').click();
  await veiculos.nth(1).locator('button[data-acao="fim-veiculo"]').click();
  await page.locator('dialog[open] #xh-ok').click();
  page.on('dialog', dialog => dialog.accept());
  await page.locator('#xo-encerrar').click();
  await page.locator('dialog[open] button').filter({ hasText: 'Confirmar encerramento' }).click();
  await page.locator('#xh-corpo button[data-acao="detalhe-historico"]').first().click();
  assert.equal(await page.locator('#xh-detalhe button').filter({ hasText: 'PDF básico (com fotos)' }).count(), 1, 'histórico oferece PDF básico com fotos');
  assert.equal(await page.locator('#xh-detalhe button').filter({ hasText: 'PDF completo (com fotos)' }).count(), 1, 'histórico oferece PDF completo com fotos');
  await page.locator('#xh-detalhe button').filter({ hasText: 'PDF básico (com fotos)' }).click();
  await page.locator('#print-area img').nth(1).waitFor({ state: 'attached' });
  assert.equal(await page.locator('#print-area img').count(), 2, 'PDF básico no histórico mantém fotos');
  await page.locator('#xh-detalhe button').filter({ hasText: 'PDF completo (com fotos)' }).click();
  await page.locator('#print-area img').nth(1).waitFor({ state: 'attached' });
  assert.equal(await page.locator('#print-area img').count(), 2, 'PDF completo no histórico mantém fotos');
  assert.deepEqual(errors, [], 'sem erros de JavaScript no navegador');
  await browser.close();
  console.log('PASS XPT E2E: criação, auditoria, G/V/P, persistência e filtros básicos.');
})().catch(e => { console.error(e); process.exit(1); });
